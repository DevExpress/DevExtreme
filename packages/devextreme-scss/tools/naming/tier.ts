/*
 * The fluent-next component tier as a pure computation, shared by tests/fluent-next-naming.test.ts
 * (the guard) and tools/naming/publish.mjs (the emitter). Nothing here touches the file system:
 * callers hand in file contents, already stripped of comments where the parser expects it.
 *
 * Paths are POSIX and relative to scss/widgets (`fluent-next/button/_colors.scss`,
 * `base/button/_index.scss`), so the module needs no knowledge of where the package lives. The file
 * is loaded natively by Node (type stripping) and through ts-jest, which is why it imports nothing
 * but `node:path` and uses erasable syntax only.
 */

import { posix } from 'node:path';

export type SourceFile = {
  /** POSIX path relative to scss/widgets. */
  path: string;
  /** First folder under the theme, `''` for theme-root files. */
  folder: string;
  raw: string;
  stripped: string;
};

export type Use = { spec: string; star: boolean; alias: string | null };
export type NamespacedReference = { namespace: string; name: string };
export type Parsed = {
  path: string;
  folder: string;
  declarations: string[];
  /*
   * `references` intentionally contains both `$name` and the `name` half of `alias.$name`, because
   * the dead-variable check must see either form. Ownership checks must not: counting a namespaced
   * read as a bare one reports the same read twice the moment the variable's name becomes canonical.
   */
  references: string[];
  bareReferences: string[];
  namespacedReferences: NamespacedReference[];
  uses: Use[];
};

export type Registries = {
  components: Record<string, string>;
  declarationHome: Record<string, string>;
  exemptFolders: Record<string, string>;
  systemTier?: string[];
  migrated: string[];
  rootSelectors: Record<string, string[]>;
};

export type TierRecord = {
  component: string;
  value: string;
  reason: string | null;
  /** Declaring files, POSIX paths relative to scss/widgets. */
  sources: string[];
};

export type WiringKind = 'star' | 'feeder';
export type WiringEntry = { folder: string; variable: string; kind: WiringKind };

export type BaseIndex = {
  names: Set<string>;
  declarationsByPath: Map<string, string[]>;
};

export const THEME = 'fluent-next';
export const DECLARATION_FILE = /(^|\/)_(colors|sizes|variables)\.scss$/;
export const CSS_WIDE_KEYWORDS = new Set(['inherit', 'initial', 'unset', 'revert', 'revert-layer']);
export const PUBLIC_FILE = '_public.scss';
export const LINKS_FILE = '_public-links.scss';
export const COLLECTOR_FILE = '_public-tier.scss';
export const GENERATED_MARKER = '// GENERATED by tools/naming/publish.mjs';

const CONTROL_DIRECTIVES = /@(if|else|each|for|while)\b[^{]*$/;
const FEEDER_CALLS = /(?:icons?-mixin|icon-colored|data-uri|toggle-delete-icon)\s*\(((?:[^()]|\([^()]*\))*)\)/g;
const DECLARATION_LINE = /^\s*(\$[a-z0-9-]+)\s*:\s*([^;]*);(.*)$/;
const LINK_LINE = /^\s*(--dx-[a-z0-9-]+)\s*:\s*var\((--dx-[a-z0-9-]+)\);\s*$/;
const PROPERTY_LINE = /^\s*(--dx-[a-z0-9-]+)\s*:/;

