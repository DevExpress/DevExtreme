export type Links = Map<string, string>; // --dx-a -> --dx-b

/** Codepoint order: what `sort()` without a comparator does, spelled out so nobody reaches for localeCompare. */
export const byCodepoint = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

export const propertyOf = (variable: string): string => `--dx-${variable.slice(1)}`;
export const variableOf = (property: string): string => `$${property.slice('--dx-'.length)}`;

/** A links file holds nothing but whole-value references; anything else is returned as a problem. */
export const parseLinksFile = (path: string, content: string): { links: Links; problems: string[] } => {
  const links: Links = new Map();
  const problems: string[] = [];
  content.split('\n').forEach((line, index) => {
    if (!PROPERTY_LINE.test(line)) return;
    const link = LINK_LINE.exec(line);
    if (!link) {
      problems.push(`${path}:${index + 1}: a links file may only hold \`--dx-a: var(--dx-b);\` lines`);
      return;
    }
    if (links.has(link[1])) problems.push(`${path}:${index + 1}: ${link[1]} is linked twice`);
    links.set(link[1], link[2]);
  });
  return { links, problems };
};

/** The `@use` spec that imports `sourcePath` from the directory of `publicPath`. */
export const useSpecFor = (publicPath: string, sourcePath: string): string => {
  const relative = posix.relative(posix.dirname(publicPath), sourcePath);
  const directory = posix.dirname(relative);
  const stem = posix.basename(relative, '.scss').replace(/^_/, '');
  return directory === '.' ? stem : posix.join(directory, stem);
};

export type Projection = { property: string; variable: string; sources: string[] };

export const renderPublicFile = (publicPath: string, projections: Projection[], hasLinks: boolean): string => {
  const specs = [...new Set(projections.flatMap(({ sources }) => sources
    .map((source) => useSpecFor(publicPath, source))))].sort(byCodepoint);
  const header = [
    GENERATED_MARKER,
    ...specs.map((spec) => `@use "${spec}" as *;`),
    ...(hasLinks ? [`@use "${LINKS_FILE.replace(/^_/, '').replace(/\.scss$/, '')}" as links;`] : []),
  ];
  const body = [...projections]
    .sort((a, b) => byCodepoint(a.property, b.property))
    .map(({ property, variable }) => `  ${property}: #{${variable}};`);
  if (hasLinks) body.push('  @include links.publish();');
  return `${header.join('\n')}\n\n@mixin publish {\n${body.join('\n')}\n}\n`;
};

export type CollectorEntry = { folder: string; selectors: string[] };

export const namespaceOf = (folder: string): string => `${folder}Public`;

/**
 * One rule per distinct selector list: the document root carries every system-tier folder and
 * stylelint forbids repeating a selector, so folders sharing a selector list share a rule.
 */
export const renderCollector = (entries: CollectorEntry[]): string => {
  const sorted = [...entries].sort((a, b) => byCodepoint(a.folder, b.folder));
  const uses = sorted.map(({ folder }) => `@use "${folder}/public" as ${namespaceOf(folder)};`);

  const groups = new Map<string, { selectors: string[]; folders: string[] }>();
  sorted.forEach(({ folder, selectors }) => {
    const key = selectors.join(',');
    const group = groups.get(key) ?? { selectors, folders: [] };
    group.folders.push(folder);
    groups.set(key, group);
  });
  const rules = [...groups.values()]
    .sort((a, b) => {
      const rootA = a.selectors.includes(':root') ? 0 : 1;
      const rootB = b.selectors.includes(':root') ? 0 : 1;
      return rootA - rootB || byCodepoint(a.folders[0], b.folders[0]);
    })
    .map(({ selectors, folders }) => `${selectors.join(',\n')} {\n${folders
      .map((folder) => `  @include ${namespaceOf(folder)}.publish();`).join('\n')}\n}`);

  return `${GENERATED_MARKER}\n${uses.join('\n')}\n\n${rules.join('\n\n')}\n`;
};

