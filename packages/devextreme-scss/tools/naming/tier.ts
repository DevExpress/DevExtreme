// the plan: every generated file, or the reasons nothing can be written
// ---------------------------------------------------------------------------------------------

export type Publication = {
  /** Generated files by path, byte-exact. Empty when `problems` is not. */
  files: Map<string, string>;
  /** Paths of `_public.scss` files that did not exist before. */
  created: string[];
  problems: string[];
};

const publicPathOf = (folder: string): string => `${THEME}/${folder}/${PUBLIC_FILE}`;
const linksPathOf = (folder: string): string => `${THEME}/${folder}/${LINKS_FILE}`;
export const COLLECTOR_PATH = `${THEME}/${COLLECTOR_FILE}`;

export const planPublication = (
  themeFiles: SourceFile[],
  baseFiles: SourceFile[],
  registries: Registries,
  existing: ReadonlyMap<string, string>,
): Publication => {
  const problems: string[] = [];
  const exempt = Object.keys(registries.exemptFolders);
  const parsedTheme = themeFiles.map(parseSourceFile);
  const wiring = new Set(baseWiringEntries(parsedTheme, baseIndex(baseFiles), exempt)
    .map(({ variable }) => variable));
  const records = tierRecords(themeFiles, registries, wiring);

  // eligible variables per component, with the folder that declares them
  const perComponent = new Map<string, Projection[]>();
  records.forEach((record, variable) => {
    if (record.reason) return;
    const list = perComponent.get(record.component) ?? [];
    list.push({ property: propertyOf(variable), variable, sources: record.sources });
    perComponent.set(record.component, list);
  });

  // hand-written links per folder
  const linksByFolder = new Map<string, Links>();
  existing.forEach((content, path) => {
    if (!path.endsWith(`/${LINKS_FILE}`)) return;
    const parsed = parseLinksFile(path, content);
    problems.push(...parsed.problems);
    linksByFolder.set(path.split('/')[1], parsed.links);
  });

  // where each component's file lives: the folder that declares its eligible variables
  const homeOf = new Map<string, string>();
  const owners = new Map<string, string>(); // property -> component
  publishingComponents(registries).forEach((component) => {
    const folders = tierFoldersOf(component, registries);
    const declaring = [...new Set((perComponent.get(component) ?? [])
      .flatMap(({ sources }) => sources.map((source) => source.split('/')[1])))];
    const linking = folders.filter((folder) => (linksByFolder.get(folder)?.size ?? 0) > 0);
    const candidates = [...new Set([...declaring, ...linking])];
    if (candidates.length > 1) {
      problems.push(`${component}: variables are declared in several folders (${candidates.join(', ')}) — one home per component`);
      return;
    }
    if (candidates.length === 1) homeOf.set(component, candidates[0]);
    (perComponent.get(component) ?? []).forEach(({ property }) => {
      const owner = owners.get(property);
      if (owner && owner !== component) problems.push(`${property} is published by both ${owner} and ${component}`);
      owners.set(property, component);
    });
    folders.forEach((folder) => {
      linksByFolder.get(folder)?.forEach((_, property) => {
        const owner = owners.get(property);
        if (owner && owner !== component) problems.push(`${property} is published by both ${owner} and ${component}`);
        owners.set(property, component);
      });
    });
  });

  const publishesOnRoot = (component: string): boolean => (registries.rootSelectors[component] ?? []).includes(':root');

  // links: a target must be published where the referrer can see it, and a link may not shadow a value
  linksByFolder.forEach((links, folder) => {
    const component = systemTierOf(registries).includes(folder) ? folder : registries.components[folder];
    links.forEach((target, property) => {
      const eligible = (perComponent.get(component) ?? []).some((projection) => projection.property === property);
      if (eligible) {
        problems.push(`${linksPathOf(folder)}: ${property} is a link, but ${variableOf(property)} is declared and eligible — remove one of the two`);
      }
      if (target === property) {
        problems.push(`${linksPathOf(folder)}: ${property} links to itself`);
        return;
      }
      const owner = owners.get(target);
      if (!owner) {
        problems.push(`${linksPathOf(folder)}: ${property} links to ${target}, which nothing publishes`);
      } else if (owner !== component && !publishesOnRoot(owner)) {
        problems.push(`${linksPathOf(folder)}: ${property} links to ${target}, published on another component's root — publish the value instead`);
      }
    });
  });

  // stray files: a public file where the component has nothing to publish, or in a foreign folder
  existing.forEach((_, path) => {
    if (!path.endsWith(`/${PUBLIC_FILE}`)) return;
    const folder = path.split('/')[1];
    const component = systemTierOf(registries).includes(folder) ? folder : registries.components[folder];
    if (!component || !publishingComponents(registries).includes(component)) {
      problems.push(`${path}: ${folder} is not a publishing component — remove the file or register the component`);
      return;
    }
    const home = homeOf.get(component);
    if (home === undefined) {
      problems.push(`${path}: ${component} has nothing left to publish — remove the file by hand`);
    } else if (home !== folder) {
      problems.push(`${path}: ${component} publishes from ${home}/ — remove this copy`);
    }
  });

  homeOf.forEach((folder, component) => {
    if (!(registries.rootSelectors[component] ?? []).length) {
      problems.push(`${component} publishes from ${folder}/ but has no rootSelectors — add it to derive-registries.mjs OVERRIDES`);
    }
  });

  if (problems.length) return { files: new Map(), created: [], problems: [...new Set(problems)].sort(byCodepoint) };

  const files = new Map<string, string>();
  const created: string[] = [];
  const collector: CollectorEntry[] = [];
  homeOf.forEach((folder, component) => {
    const path = publicPathOf(folder);
    const hasLinks = (linksByFolder.get(folder)?.size ?? 0) > 0;
    files.set(path, renderPublicFile(path, perComponent.get(component) ?? [], hasLinks));
    if (!existing.has(path)) created.push(path);
    collector.push({ folder, selectors: registries.rootSelectors[component] });
  });
  files.set(COLLECTOR_PATH, renderCollector(collector));

  return { files, created: created.sort(byCodepoint), problems: [] };
};

/** Paths whose committed content differs from the plan — what `--check` reports. */
export const stalePaths = (plan: Publication, existing: ReadonlyMap<string, string>): string[] => [...plan.files]
  .filter(([path, content]) => existing.get(path) !== content)
  .map(([path]) => path)
  .sort(byCodepoint);
