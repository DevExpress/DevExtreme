/**
 * `base/**` parameter names, keyed by file so a star import can be resolved to the exact module it
 * pulls in. The wide question ("does base declare this name anywhere") would wave through any
 * legacy name; the precise one is asked by `starredBaseParameters`.
 */
export const baseIndex = (baseFiles: SourceFile[]): BaseIndex => {
  const declarationsByPath = new Map<string, string[]>();
  const names = new Set<string>();
  baseFiles.forEach((file) => {
    const { declarations } = parseSourceFile(file);
    declarationsByPath.set(file.path, declarations);
    declarations.forEach((name) => names.add(name));
  });
  return { names, declarationsByPath };
};

/**
 * The base parameters a theme file wires by star-importing the very base module that declares them:
 * a top-level `$x: … !default` there SETS base's variable, so the name is base's spelling.
 */
export const starredBaseParameters = (parsed: Parsed, index: BaseIndex): Set<string> => {
  const names = new Set<string>();
  parsed.uses.forEach(({ spec, star }) => {
    if (!star || !spec.includes('base/')) return;
    const directory = posix.normalize(posix.join(posix.dirname(parsed.path), spec, '..'));
    const stem = spec.split('/').pop() as string;
    [posix.join(directory, `_${stem}.scss`), posix.join(directory, stem, '_index.scss')]
      .forEach((candidate) => (index.declarationsByPath.get(candidate) ?? [])
        .forEach((name) => names.add(name)));
  });
  return names;
};

/*
 * Base wiring is configuration, not ownership. Two shapes, both structural:
 *   - star: the file star-imports the very base module that declares the name, and the top-level
 *     `$x: … !default` SETS base's variable.
 *   - feeder: `$fluent-<baseName>` passed as a `with()` value for base's `-2` key.
 */
export const baseWiringKind = (variable: string, parsed: Parsed, index: BaseIndex): WiringKind | null => {
  if (starredBaseParameters(parsed, index).has(variable)) return 'star';
  if (variable.startsWith('$fluent-') && index.names.has(`$${variable.slice('$fluent-'.length)}`)) {
    return 'feeder';
  }
  return null;
};

export const baseWiringEntries = (
  parsedTheme: Parsed[],
  index: BaseIndex,
  exemptFolders: string[],
): WiringEntry[] => parsedTheme
  .flatMap((parsed) => parsed.declarations
    .map((variable) => ({ folder: parsed.folder, variable, kind: baseWiringKind(variable, parsed, index) }))
    .filter((entry): entry is WiringEntry => entry.kind !== null && !exemptFolders.includes(entry.folder)));

