export const systemTierOf = (registries: Registries): string[] => registries.systemTier ?? [];

export const tierFoldersOf = (component: string, registries: Registries): string[] => {
  if (systemTierOf(registries).includes(component)) return [component];
  const exempt = Object.keys(registries.exemptFolders);
  const folders = Object.entries(registries.components)
    .filter(([, owner]) => owner === component)
    .map(([folder]) => folder);
  const home = registries.declarationHome[component];
  if (home && !folders.includes(home)) folders.push(home);
  return folders.filter((folder) => !exempt.includes(folder));
};

/** Components that may publish: migrated plus the system tier, each once. */
export const publishingComponents = (registries: Registries): string[] => [
  ...new Set([...registries.migrated, ...systemTierOf(registries)]),
];

const inFolder = (file: SourceFile, folder: string): boolean => file.path.startsWith(`${THEME}/${folder}/`);

/** Which variables the tier MUST declare, and why the rest are excluded. */
export const tierRecords = (
  themeFiles: SourceFile[],
  registries: Registries,
  wiring: ReadonlySet<string>,
): Map<string, TierRecord> => {
  const records = new Map<string, TierRecord>();

  publishingComponents(registries).forEach((component) => {
    const declared = new Map<string, { value: string; marker: boolean; sources: string[] }>();
    const feeders = new Set<string>();
    tierFoldersOf(component, registries).forEach((folder) => {
      themeFiles.filter((file) => inFolder(file, folder)).forEach((file) => {
        if (DECLARATION_FILE.test(file.path)) {
          file.stripped.split('\n').forEach((line) => {
            const match = DECLARATION_LINE.exec(line);
            if (!match) return;
            const previous = declared.get(match[1]);
            const sources = previous?.sources ?? [];
            if (!sources.includes(file.path)) sources.push(file.path);
            declared.set(match[1], {
              value: match[2].trim().replace(/\s*!default$/, ''),
              marker: (previous?.marker ?? false) || /dx-data-uri-static/.test(match[3] + match[2]),
              sources,
            });
          });
        }
        // Feeder calls are read from the RAW file on purpose: a commented-out call still documents
        // that the variable bakes into an image somewhere.
        [...file.raw.matchAll(FEEDER_CALLS)]
          .forEach((call) => [...call[1].matchAll(/\$[a-z0-9-]+/g)]
            .forEach(([variable]) => feeders.add(variable)));
      });
    });
    declared.forEach(({ value, marker, sources }, variable) => {
      const reason = marker || feeders.has(variable) || /(^|[^\w-])data-uri\(/.test(value)
        ? 'data-uri'
        : wiring.has(variable) ? 'base-wiring'
          : CSS_WIDE_KEYWORDS.has(value) ? 'css-wide-keyword'
            : value.includes('!important') ? 'important'
              : value === 'null' ? 'null'
                : value === 'false' || value === 'true' ? 'sass-flag' : null;
      records.set(variable, {
        component, value, reason, sources,
      });
    });
  });

  // a reference to a data-uri-excluded name carries the same baked image, so the referrer is excluded too
  for (let changed = true; changed;) {
    changed = false;
    records.forEach((record) => {
      if (record.reason) return;
      if ([...record.value.matchAll(/\$[a-z0-9-]+/g)]
        .some(([token]) => records.get(token)?.reason === 'data-uri')) {
        record.reason = 'data-uri';
        changed = true;
      }
    });
  }
  return records;
};

